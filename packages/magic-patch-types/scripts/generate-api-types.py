"""Generate the supported frontend DTO subset from api/openapi.json.

This validates local refs and fails on unsupported schema constructs rather
than silently generating any. It is not a complete OpenAPI validator/client.
"""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
spec = json.loads((root / "openapi.json").read_text())

def check_refs(value):
    if isinstance(value, dict):
        if "$ref" in value:
            target = spec
            for component in value["$ref"].removeprefix("#/").split("/"):
                target = target[component]
        for item in value.values():
            check_refs(item)
    elif isinstance(value, list):
        for item in value:
            check_refs(item)

def ts(schema):
    if schema.get("nullable"):
        return ts({k:v for k,v in schema.items() if k != "nullable"}) + " | null"
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    kind = schema["type"]
    if kind in ("string", "boolean"):
        return kind
    if kind in ("integer", "number"):
        return "number"
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        if schema.get("additionalProperties") is True and not schema.get("properties"):
            return "Record<string, unknown>"
        if schema.get("additionalProperties") is not False:
            raise ValueError("DTO objects must have explicit closed properties")
        required = schema.get("required", [])
        properties = schema["properties"]
        if set(required) - properties.keys():
            raise ValueError("required property missing")
        return "{\n" + "\n".join(
            "  " + json.dumps(name) + ("" if name in required else "?") + ": " + ts(value) + ";"
            for name, value in properties.items()
        ) + "\n}"
    raise ValueError("unsupported schema type " + kind)

def zod(schema):
    if schema.get("nullable"):
        return zod({k:v for k,v in schema.items() if k != "nullable"}) + ".nullable()"
    if "$ref" in schema:
        return "z" + schema["$ref"].split("/")[-1]
    if "enum" in schema:
        if schema.get("type") == "integer":
            return "z.literal(" + json.dumps(schema["enum"][0]) + ")"
        return "z.enum(" + json.dumps(schema["enum"]) + ")"
    kind = schema["type"]
    if kind == "object":
        if schema.get("additionalProperties") is True and not schema.get("properties"):
            return "z.record(z.string(), z.unknown())"
        required = schema.get("required", [])
        expression = "z.object({\n" + "\n".join(
            "  " + json.dumps(name) + ": " + zod(value) + ("" if name in required else ".optional()") + ","
            for name, value in schema["properties"].items()
        ) + "\n}).strict()"
        if "anyOf" in schema:
            if any(set(branch) != {"required"} for branch in schema["anyOf"]):
                raise ValueError("unsupported object alternatives")
            alternatives = ["(" + " && ".join("value[" + json.dumps(name) + "] !== undefined" for name in branch["required"]) + ")" for branch in schema["anyOf"]]
            expression += ".refine(value => " + " || ".join(alternatives) + ")"
        return expression
    expressions = {"string": "z.string()", "boolean": "z.boolean()", "integer": "z.number().int().safe()", "number": "z.number()"}
    expression = "z.array(" + zod(schema["items"]) + ")" if kind == "array" else expressions[kind]
    if "pattern" in schema:
        expression += ".regex(new RegExp(" + json.dumps(schema["pattern"]) + "))"
    for constraint, method in [("minLength", "min"), ("maxLength", "max"), ("minimum", "min"), ("maximum", "max"), ("minItems", "min"), ("maxItems", "max")]:
        if constraint in schema:
            expression += "." + method + "(" + str(schema[constraint]) + ")"
    if schema.get("uniqueItems"):
        if kind != "array" or schema["items"].get("type") != "string":
            raise ValueError("unsupported unique item type")
        expression += ".refine(value => new Set(value).size === value.length)"
    return expression

check_refs(spec)
output = "// Generated by scripts/generate-api-types.py. Draft contract; routes are unwired.\n"
output += "// Validation constraints and authorization semantics remain in api/openapi.json.\n\n"
for name, schema in spec["components"]["schemas"].items():
    output += "export type " + name + " = " + ts(schema) + ";\n\n"
output = output.rstrip() + "\n"
destination = root / "src/types.generated.ts"
zod_output = "// Generated by scripts/generate-api-types.py. Draft contract; routes are unwired.\nimport { z } from 'zod'\n\n"
for name, schema in spec["components"]["schemas"].items():
    zod_output += "export const z" + name + " = " + zod(schema) + "\n\n"
zod_output = zod_output.rstrip() + "\n"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
for path, content in [(destination, output), (root / "src/zod.generated.ts", zod_output)]:
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("generated contract differs; run generator")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")
print("OpenAPI references and generated DTOs checked" if args.check else "DTOs generated")
