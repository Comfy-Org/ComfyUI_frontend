/**
 * What this pack is pinned to, whatever form its manifest uses.
 *
 * Core rows carry a git commit; cloud rows carry the deployRef Cloud actually
 * ships - `owner/repo@sha` for git-sourced packs, `id@version` for registry
 * packs, which the registry distributes as a CDN artifact and for which no
 * commit exists. Callers recording provenance want the identity, not the form.
 */
export function packIdentity(
  entry: CoreManifestEntry | CloudManifestEntry
): string {
  return 'deployRef' in entry ? entry.deployRef : entry.pin
}

interface QuarantineDetails {
  reason: string
  evidence: string
  upstreamFix: string
  since: string
}

export type QuarantinedPack = QuarantineDetails &
  (
    | { class: 'unfetchable-ref'; failurePattern?: never }
    | { class: 'unsatisfiable-requirement'; failurePattern: string }
    | { class: 'requires-gpu-runner'; failurePattern?: never }
  )

// Packs this local CPU gate cannot exercise. Network-verifiable source failures
// are rechecked by the workflow; hardware exclusions remain visible in every
// Actions summary until a GPU-backed shard restores their coverage.
export function loadPackQuarantine(): Record<string, QuarantinedPack> {
  const path = dataPath('cloud/packQuarantine.json')
  if (!existsSync(path)) return {}
  const parsed: unknown = JSON.parse(readFileSync(path, 'utf-8'))
  if (!isRecord(parsed))
    throw new Error(`${path} must be a JSON object keyed by pack name`)
  const entries: Record<string, QuarantinedPack> = {}
  const manifestPacks = new Set(
    readCloudManifest().packs.map(({ pack }) => pack)
  )
  for (const [pack, entry] of Object.entries(parsed)) {
    if (!manifestPacks.has(pack))
      throw new Error(`${path}: ${pack} is not in the cloud manifest`)
    if (
      !isRecord(entry) ||
      (entry.class !== 'unfetchable-ref' &&
        entry.class !== 'unsatisfiable-requirement' &&
        entry.class !== 'requires-gpu-runner') ||
      !isNonEmptyString(entry.reason) ||
      !isNonEmptyString(entry.evidence) ||
      (entry.class === 'unsatisfiable-requirement' &&
        !isNonEmptyString(entry.failurePattern)) ||
      !isNonEmptyString(entry.upstreamFix) ||
      !isIsoDate(entry.since)
    )
      throw new Error(`${path}: ${pack} has an invalid quarantine entry`)
    if (entry.class === 'unsatisfiable-requirement') {
      if (!isNonEmptyString(entry.failurePattern))
        throw new Error(`${path}: ${pack} has an invalid quarantine entry`)
      entries[pack] = {
        class: entry.class,
        reason: entry.reason,
        evidence: entry.evidence,
        failurePattern: entry.failurePattern,
        upstreamFix: entry.upstreamFix,
        since: entry.since
      }
    } else {
      entries[pack] = {
        class: entry.class,
        reason: entry.reason,
        evidence: entry.evidence,
        upstreamFix: entry.upstreamFix,
        since: entry.since
      }
    }
  }
  return entries
}

export function loadManifest(): (CoreManifestEntry | CloudManifestEntry)[] {
  const shard = manifestShard()
  if (
    customNodesManifest() === 'cloud' &&
    customNodesBackend() === 'local' &&
    shard !== null &&
    shard.total !== CLOUD_LOCAL_CALIBRATION_SHARDS
  )
    throw new Error(
      `cloud/local expectations are calibrated for ${CLOUD_LOCAL_CALIBRATION_SHARDS} shards, got ${shard.total}; recalibrate the exact node, persistence, and connectivity contracts before changing the matrix`
    )
  // Assign over the FULL manifest, then drop the excluded packs. Packing the
  // filtered list instead made shard composition depend on the exclusion
  // ledgers: moving four packs out of quarantine moved 26 of 81 packs to a
  // different shard. All packs in a shard share one Python environment, so a
  // pack's neighbours decide which of its optional imports resolve and how
  // many node classes it registers - WanVideoWrapper measured 141, 142 and 146
  // across three runs without its own pin changing. Composition now moves only
  // when the manifest does.
  const quarantined =
    customNodesManifest() === 'cloud' ? loadPackQuarantine() : {}
  return shardOf(loadFullManifest(), (entry) => entry.expectedNodeCount).filter(
    (entry) => !(entry.pack in quarantined)
  )
}

/** Every pack the manifest declares, ignoring the shard slice. */
export function loadFullManifest(): (CoreManifestEntry | CloudManifestEntry)[] {
  if (customNodesManifest() === 'cloud') return readCloudManifest().packs
  return readCoreManifest()
}

export function loadApplicableAutogrowCases() {
  const full = loadFullManifest()
  const shard = new Set(loadManifest().map((entry) => entry.pack))
  return AUTOGROW_CASES.flatMap((autogrowCase) => {
    const manifestEntry = full.find(
      (entry) => entry.pack.toLowerCase() === autogrowCase.pack.toLowerCase()
    )
    // Stale AUTOGROW_CASES is a manifest-wide fact and must fail everywhere;
    // whether this shard runs the pack is a separate question below.
    if (!manifestEntry)
      throw new Error(
        `${autogrowCase.pack} is not a manifest pack - fix AUTOGROW_CASES`
      )
    if (!shard.has(manifestEntry.pack)) return []
    return expectedExtensionsFor(manifestEntry).includes(
      autogrowCase.extensionName
    )
      ? [{ autogrowCase, manifestEntry }]
      : []
  })
}
